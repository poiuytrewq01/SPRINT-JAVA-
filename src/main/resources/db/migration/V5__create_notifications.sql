-- =====================================================================
-- V5 - Notificacoes entregues pela fila do RabbitMQ
--
-- Cada linha e o resultado do processamento de uma mensagem pelo
-- NotificationConsumer. A tabela nao e escrita pelos services de negocio:
-- eles apenas publicam eventos, e o consumidor e quem grava aqui.
--
-- Migration nova, e nao alteracao da V2 ou da V3: scripts ja aplicados
-- nunca sao editados (o Flyway recusaria o checksum diferente).
-- =====================================================================

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Identificador do evento gerado pelo produtor. A constraint unica e a
    -- garantia de idempotencia no banco: uma mensagem reentregue pelo broker
    -- nao gera uma segunda notificacao.
    event_id    UUID         NOT NULL,
    user_id     BIGINT       NOT NULL,
    type        VARCHAR(30)  NOT NULL,
    message     VARCHAR(300) NOT NULL,
    -- Caminho interno da aplicacao, nunca uma URL externa.
    link        VARCHAR(200) NOT NULL,
    occurred_at TIMESTAMP    NOT NULL,
    read_at     TIMESTAMP,

    CONSTRAINT uk_notifications_event UNIQUE (event_id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_link_interno CHECK (link LIKE '/%' AND link NOT LIKE '//%'),
    CONSTRAINT ck_notifications_type CHECK (
        type IN ('LINK_REQUESTED', 'LINK_APPROVED', 'LINK_REJECTED', 'RETURN_SCHEDULED')
    )
);

-- Atende as duas consultas da tela: as mais recentes do usuario e a
-- contagem de nao lidas exibida no menu.
CREATE INDEX idx_notifications_user_occurred ON notifications (user_id, occurred_at DESC);
CREATE INDEX idx_notifications_user_unread   ON notifications (user_id) WHERE read_at IS NULL;
